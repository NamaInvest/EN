"""Extract meaningful relationships from graphify graph.json into separate insight files.

Each output file targets a specific architectural question:
1. God nodes (most-connected) — refactor candidates
2. Cross-community bridges — hidden coupling between subsystems
3. Weak communities (low cohesion) — split candidates
4. INFERRED edges — model-reasoned relationships needing human verification
5. Engine pattern proliferation — DRY/abstract base candidates
6. Saudi compliance footprint — ZATCA, GOSI, WPS, Mudad, Nitaqat, PDPL distribution
7. Files spanning multiple communities — natural module boundary violators
8. Module coupling matrix — top community-to-community link counts
9. Isolated / orphan nodes — dead code candidates
10. Auto-journal central hub — every accounting integration point in one place
"""
from __future__ import annotations
import json
from collections import Counter, defaultdict
from pathlib import Path

GRAPH = Path("graphify-out/graph.json")
LABELS = Path("graphify-out/wiki/index.md")  # not used; rebuild labels from analysis if needed
OUT = Path("C:/Users/1/Desktop/namasoft-graph-insights")
OUT.mkdir(parents=True, exist_ok=True)


def load() -> tuple[dict, dict, dict, dict]:
    data = json.loads(GRAPH.read_text(encoding="utf-8"))
    nodes = {n["id"]: n for n in data["nodes"]}
    edges = data.get("links") or data.get("edges") or []
    # community label from node attribute; build label dict
    comms: dict[int, list[str]] = defaultdict(list)
    for nid, n in nodes.items():
        comms[n.get("community", -1)].append(nid)
    return nodes, edges, dict(comms), data


def write(name: str, body: str) -> None:
    p = OUT / name
    p.write_text(body, encoding="utf-8")
    print(f"  wrote {p.name} ({len(body):,} chars)")


def fname(nodes: dict, nid: str) -> str:
    return nodes[nid].get("source_file", "?")


def lbl(nodes: dict, nid: str) -> str:
    return nodes[nid].get("label", nid)


def comm_of(nodes: dict, nid: str) -> int:
    return nodes[nid].get("community", -1)


