# ---------- 02 Cross-community bridges ----------
def emit_bridges(nodes, edges, comms):
    # Count cross-community edges per node
    bridge_score = Counter()
    bridge_targets: dict[str, set[int]] = defaultdict(set)
    for e in edges:
        s, t = e["source"], e["target"]
        cs, ct = comm_of(nodes, s), comm_of(nodes, t)
        if cs != ct and cs >= 0 and ct >= 0:
            bridge_score[s] += 1
            bridge_score[t] += 1
            bridge_targets[s].add(ct)
            bridge_targets[t].add(cs)

    top = bridge_score.most_common(30)
    lines = ["# 02 — Cross-Community Bridges\n",
             "_Nodes that span the most distinct communities. They couple subsystems that the cluster algorithm thinks should be separate._\n",
             "\n## Top 30 bridges\n",
             "| Rank | Node | Distinct communities reached | Total cross-edges | File | Home community |",
             "|------|------|------------------------------|-------------------|------|----------------|"]
    for rank, (nid, score) in enumerate(top, 1):
        reach = len(bridge_targets[nid])
        n = nodes.get(nid, {})
        lines.append(f"| {rank} | `{lbl(nodes, nid)}` | {reach} | {score} | `{n.get('source_file','?')}` | C{comm_of(nodes, nid)} |")

    lines.append("\n## Architectural read\n")
    lines.append("- A bridge node reaching 8+ communities is rarely a bug — it's usually infrastructure (`getPrisma`, `db`, `n` for decimals). Verify the abstraction is intentional, not accidental.\n")
    lines.append("- Bridges in *business logic* communities are red flags. If a domain function (e.g. `calculateZakat`) reaches 5+ unrelated communities, it's doing too much.\n")
    lines.append("- Compare each top bridge against CLAUDE.md rule 3.3 (multi-tenant). Anything that bypasses tenant scoping should not appear here.\n")
    write("02_cross_community_bridges.md", "\n".join(lines))


# ---------- 03 Weak communities ----------
def emit_weak_communities(nodes, edges, comms):
    # Compute internal/external edge ratio per community
    internal = Counter()
    external = Counter()
    for e in edges:
        cs = comm_of(nodes, e["source"])
        ct = comm_of(nodes, e["target"])
        if cs == ct:
            internal[cs] += 1
        else:
            external[cs] += 1
            external[ct] += 1

    rows = []
    for cid, members in comms.items():
        if cid < 0 or len(members) < 4:
            continue
        i, x = internal[cid], external[cid]
        ratio = i / (i + x) if (i + x) > 0 else 0
        rows.append((cid, len(members), i, x, ratio))
    rows.sort(key=lambda r: r[4])  # weakest first

    lines = ["# 03 — Weak Communities (split / rename candidates)\n",
             "_Communities of size ≥ 4 with the lowest internal cohesion ratio. Low ratio = nodes are linked more to outsiders than to each other → poor naming or wrong grouping._\n",
             "\n## Bottom 25 by internal-edge ratio\n",
             "| Rank | C# | Size | Internal edges | External edges | Internal ratio | Sample members |",
             "|------|----|------|----------------|----------------|----------------|----------------|"]

    # Need labels from analysis JSON; fall back to "C#"
    for rank, (cid, sz, i, x, r) in enumerate(rows[:25], 1):
        sample = ", ".join(lbl(nodes, m) for m in comms[cid][:5])
        lines.append(f"| {rank} | C{cid} | {sz} | {i} | {x} | {r:.2%} | {sample} |")

    lines.append("\n## Architectural read\n")
    lines.append("- A 47-node community with internal ratio under 30% is not a module — it's a folder. Split it.\n")
    lines.append("- The `Auto-Journal Engine` cluster (47 nodes, cohesion 0.06 in the report) is the largest. It's structurally weak because `auto-journal.ts` calls many domain engines (Zakat, EOS, RMA, Numbering) — those engines should be siblings, not members. Consider promoting them to their own communities and keeping auto-journal as just the dispatcher.\n")
    lines.append("- Communities under 30% ratio with mixed-domain names (e.g. `Audit + Bank Recon + Dunning`) usually indicate the cluster algorithm caught accidental coupling through shared infra (logger, prisma, audit).\n")
    write("03_weak_communities.md", "\n".join(lines))


# ---------- 04 INFERRED edges ----------
def emit_inferred(nodes, edges, comms):
    inferred = [e for e in edges if e.get("confidence") == "INFERRED"]
    ambiguous = [e for e in edges if e.get("confidence") == "AMBIGUOUS"]

    by_source = Counter(e["source"] for e in inferred)
    top_inferred = by_source.most_common(20)

    lines = [f"# 04 — INFERRED Edges to Verify\n",
             f"_Total INFERRED: **{len(inferred)}** ({len(inferred)/len(edges):.1%} of all edges) · AMBIGUOUS: **{len(ambiguous)}**_\n",
             "\nINFERRED edges are model-reasoned relationships (not literal imports or calls). They often catch real semantic links AST cannot see, but each needs review.\n",
             "\n## Top 20 sources of INFERRED edges\n",
             "| Source node | INFERRED out-edges | File |",
             "|-------------|--------------------|----- |"]
    for nid, c in top_inferred:
        lines.append(f"| `{lbl(nodes, nid)}` | {c} | `{nodes.get(nid, {}).get('source_file','?')}` |")

    lines.append("\n## All INFERRED edges (sorted by confidence_score)\n")
    inferred_sorted = sorted(inferred, key=lambda e: -e.get("confidence_score", 0))
    lines.append("| Confidence | Source | Relation | Target | File |")
    lines.append("|------------|--------|----------|--------|------|")
    for e in inferred_sorted[:80]:
        lines.append(f"| {e.get('confidence_score', 0):.2f} | `{lbl(nodes, e['source'])}` | {e['relation']} | `{lbl(nodes, e['target'])}` | `{e.get('source_file','?')}` |")

    if len(inferred_sorted) > 80:
        lines.append(f"\n_(+{len(inferred_sorted)-80} more — full list in `graph.json`.)_")

    lines.append("\n## Architectural read\n")
    lines.append("- AST-only mode produces fewer INFERRED edges than semantic mode — these are AST's best guesses about indirect relationships.\n")
    lines.append("- Review the highest-confidence INFERRED edges first: if they're wrong, the heuristic is broken; if right, treat them as undocumented dependencies and add explicit imports.\n")
    write("04_inferred_edges_to_verify.md", "\n".join(lines))


# ---------- 05 Engine pattern proliferation ----------
def emit_engines(nodes, edges, comms):
    engines = []
    for nid, n in nodes.items():
        label = n.get("label", "")
        if label.endswith("Engine") and not label.startswith("."):
            engines.append((nid, label, n.get("source_file", "?")))

    # Methods grouped by engine
    methods_by_engine: dict[str, list[str]] = defaultdict(list)
    for nid, n in nodes.items():
        sf = n.get("source_file", "")
        label = n.get("label", "")
        if label.startswith(".") and sf:
            # Find engine class in same file
            for eid, elabel, esf in engines:
                if esf == sf:
                    methods_by_engine[elabel].append(label)
                    break

    lines = [f"# 05 — `*Engine` Pattern Proliferation\n",
             f"_Found **{len(engines)}** classes named `*Engine` across `src/lib`._\n",
             "\nThis is the most common pattern in the codebase. Question: do they share enough surface area to deserve a shared base class?\n",
             "\n## Method-name frequency across all engines\n",
             "_If a method name appears on many engines, it's a candidate for an abstract base method or a shared interface._\n"]

    method_freq = Counter()
    for methods in methods_by_engine.values():
        for m in set(methods):
            method_freq[m] += 1

    lines.append("| Method | # of engines that have it |")
    lines.append("|--------|--------------------------|")
    for m, c in method_freq.most_common(25):
        if c >= 3:
            lines.append(f"| `{m}` | {c} |")

    lines.append("\n## All engines (alphabetical)\n")
    lines.append("| Engine | File | # of methods detected |")
    lines.append("|--------|------|----------------------|")
    for nid, label, sf in sorted(engines, key=lambda x: x[1]):
        lines.append(f"| `{label}` | `{sf}` | {len(set(methods_by_engine.get(label, [])))} |")

    lines.append("\n## Architectural read\n")
    lines.append("- `.create()`, `.list()`, `.update()`, `.delete()`, `.constructor()` are repeated across most engines — strong case for an `EntityEngine<T>` base or for using a generic CRUD service generator.\n")
    lines.append("- Domain-specific methods (`.calculateGOSI`, `.runMRP`, `.recognizeLease`) are unique — keep those concrete.\n")
    lines.append("- Before abstracting: check if the engines actually share parameter shapes, error contracts, transaction boundaries. Premature inheritance is worse than copy-paste.\n")
    write("05_engine_pattern_proliferation.md", "\n".join(lines))


# ---------- 06 Saudi compliance footprint ----------
def emit_saudi(nodes, edges, comms):
    # Match by source_file or label keywords
    keywords = {
        "ZATCA": ["zatca", "fatoora"],
        "GOSI": ["gosi"],
        "WPS": ["wps", "sif"],
        "Mudad": ["mudad"],
        "Nitaqat / Saudization": ["nitaqat", "saudization"],
        "PDPL / DSR": ["pdpl", "dsr", "consent"],
        "Hijri": ["hijri"],
        "Zakat": ["zakat"],
        "WHT": ["wht", "withholding"],
        "EOS (End of Service)": ["eos", "end-of-service", "saudi-eos"],
        "VAT": ["vat-classifier", "vat_"],
        "Arabic i18n": ["arabic", "formatters", "translations"],
    }

    matches: dict[str, list[str]] = {k: [] for k in keywords}
    for nid, n in nodes.items():
        sf = n.get("source_file", "").lower()
        label = n.get("label", "").lower()
        for area, kws in keywords.items():
            for kw in kws:
                if kw in sf or kw in label:
                    matches[area].append(nid)
                    break

    lines = ["# 06 — Saudi Compliance Footprint\n",
             "_Where each Saudi-specific compliance area lives in the codebase, by node count._\n",
             "\n| Area | # nodes | Files |",
             "|------|---------|-------|"]
    for area in sorted(keywords, key=lambda a: -len(matches[a])):
        ms = matches[area]
        files = sorted({nodes[m].get("source_file", "?") for m in ms})
        files_str = ", ".join(f"`{f}`" for f in files[:6])
        if len(files) > 6:
            files_str += f", _(+{len(files)-6} more)_"
        lines.append(f"| **{area}** | {len(ms)} | {files_str} |")

    lines.append("\n## Per-area drill-down\n")
    for area in sorted(keywords, key=lambda a: -len(matches[a])):
        ms = matches[area]
        if not ms:
            continue
        lines.append(f"\n### {area} ({len(ms)} nodes)\n")
        for nid in sorted(ms, key=lambda i: nodes[i].get("source_file", ""))[:30]:
            lines.append(f"- `{lbl(nodes, nid)}` — `{nodes[nid].get('source_file','?')}` (C{comm_of(nodes,nid)})")
        if len(ms) > 30:
            lines.append(f"- _(+{len(ms)-30} more)_")

    lines.append("\n## Architectural read\n")
    lines.append("- ZATCA has the largest footprint by far — multiple modules (`zatca-signer`, `zatca-java-adapter`, `zatca-clearance`, `zatca-tlv`, `zatca-xml-hash`). Fragmentation is fine if cohesion is high; check community 11/36/48/148.\n")
    lines.append("- Mudad and Nitaqat are isolated — small, focused, easy to update when government rules change.\n")
    lines.append("- PDPL/DSR with multiple files (`checkConsent`, `createDSR`, `eraseSubject`, `getOverdueDSRs`) suggests good coverage of GDPR-style obligations. Verify against PDPL Article 19 (data subject rights).\n")
    write("06_saudi_compliance_footprint.md", "\n".join(lines))


# ---------- 07 Files spanning communities ----------
def emit_spanning_files(nodes, edges, comms):
    file_to_comms: dict[str, set[int]] = defaultdict(set)
    file_to_nodes: dict[str, list[str]] = defaultdict(list)
    for nid, n in nodes.items():
        sf = n.get("source_file", "")
        if not sf:
            continue
        c = comm_of(nodes, nid)
        if c >= 0:
            file_to_comms[sf].add(c)
            file_to_nodes[sf].append(nid)

    rows = []
    for sf, cs in file_to_comms.items():
        if len(cs) >= 3:
            rows.append((sf, len(cs), len(file_to_nodes[sf]), sorted(cs)))
    rows.sort(key=lambda r: -r[1])

    lines = ["# 07 — Files Spanning Multiple Communities\n",
             "_Files whose nodes are scattered across ≥ 3 communities. Either the file is a true facade (auto-journal.ts) or it's grown into a god file that should be split._\n",
             "\n| Rank | File | # of communities | Total nodes | Communities |",
             "|------|------|------------------|-------------|-------------|"]
    for rank, (sf, n_comms, n_nodes, cs) in enumerate(rows[:30], 1):
        lines.append(f"| {rank} | `{sf}` | {n_comms} | {n_nodes} | {', '.join('C'+str(c) for c in cs)} |")

    lines.append("\n## Architectural read\n")
    lines.append("- Top of this list is your candidate for the largest refactor effort — splitting one file into its constituent responsibilities.\n")
    lines.append("- A file at #1 with 7+ communities means its functions handle wildly different concerns and the test coverage probably mirrors the chaos.\n")
    write("07_files_spanning_communities.md", "\n".join(lines))


# ---------- 08 Module coupling matrix ----------
def emit_coupling(nodes, edges, comms, comm_labels: dict[int, str] | None = None):
    pair_count = Counter()
    for e in edges:
        cs = comm_of(nodes, e["source"])
        ct = comm_of(nodes, e["target"])
        if cs != ct and cs >= 0 and ct >= 0:
            key = tuple(sorted([cs, ct]))
            pair_count[key] += 1

    lines = ["# 08 — Module Coupling Matrix (top community-to-community links)\n",
             "_Pairs of communities with the most cross-edges. Strong coupling that the cluster algorithm chose NOT to merge them suggests the connection is a domain interface, not internal cohesion._\n",
             "\n| Rank | Community A | Community B | Cross-edges |",
             "|------|-------------|-------------|-------------|"]
    for rank, ((a, b), c) in enumerate(pair_count.most_common(40), 1):
        la = (comm_labels or {}).get(a, f"C{a}") if comm_labels else f"C{a}"
        lb = (comm_labels or {}).get(b, f"C{b}") if comm_labels else f"C{b}"
        lines.append(f"| {rank} | C{a} {la} | C{b} {lb} | {c} |")

    lines.append("\n## Architectural read\n")
    lines.append("- Top 5 pairs are your real subsystem interfaces — document them as ADRs.\n")
    lines.append("- Pairs with 10+ cross-edges where neither side is infrastructure (db, cache, logger) are coupling smells.\n")
    write("08_module_coupling_matrix.md", "\n".join(lines))


# ---------- 09 Isolated nodes ----------
def emit_isolated(nodes, edges, comms):
    deg = Counter()
    for e in edges:
        deg[e["source"]] += 1
        deg[e["target"]] += 1

    isolated = [nid for nid in nodes if deg[nid] == 0]
    near = [(nid, deg[nid]) for nid in nodes if 0 < deg[nid] <= 1]

    lines = [f"# 09 — Isolated / Near-Isolated Nodes\n",
             f"_**{len(isolated)}** nodes have zero connections. **{len(near)}** have exactly 1. Either dead code, entry points (test files), or extraction missed something._\n",
             "\n## Zero-degree nodes (first 60)\n",
             "| Node | File | Community |",
             "|------|------|-----------|"]
    for nid in sorted(isolated, key=lambda i: nodes[i].get("source_file",""))[:60]:
        lines.append(f"| `{lbl(nodes, nid)}` | `{nodes[nid].get('source_file','?')}` | C{comm_of(nodes,nid)} |")
    if len(isolated) > 60:
        lines.append(f"\n_(+{len(isolated)-60} more zero-degree nodes)_\n")

    lines.append("\n## Degree-1 nodes (first 40)\n")
    lines.append("| Node | File |")
    lines.append("|------|------|")
    for nid, d in sorted(near, key=lambda x: nodes[x[0]].get("source_file",""))[:40]:
        lines.append(f"| `{lbl(nodes, nid)}` | `{nodes[nid].get('source_file','?')}` |")

    lines.append("\n## Architectural read\n")
    lines.append("- AST-only extraction misses runtime imports (e.g. dynamic `await import()`). A zero-degree node may still be used — check before deleting.\n")
    lines.append("- Test files appearing here is normal (they import the SUT but rarely export anything imported elsewhere).\n")
    lines.append("- Real dead code candidates: utility functions in `*-utils.ts` files with degree 0 that are not tests. Start there.\n")
    write("09_isolated_nodes.md", "\n".join(lines))


# ---------- 10 Auto-journal hub ----------
def emit_auto_journal(nodes, edges, comms):
    # Find auto-journal nodes
    aj_ids = [nid for nid, n in nodes.items() if "auto-journal" in n.get("source_file", "")]
    aj_set = set(aj_ids)

    # Edges where one end is in auto-journal
    incoming = [e for e in edges if e["target"] in aj_set and e["source"] not in aj_set]
    outgoing = [e for e in edges if e["source"] in aj_set and e["target"] not in aj_set]

    # Group incoming by source file (callers)
    callers = defaultdict(list)
    for e in incoming:
        callers[nodes[e["source"]].get("source_file", "?")].append((lbl(nodes, e["source"]), lbl(nodes, e["target"]), e["relation"]))
    callees = defaultdict(list)
    for e in outgoing:
        callees[nodes[e["target"]].get("source_file", "?")].append((lbl(nodes, e["source"]), lbl(nodes, e["target"]), e["relation"]))

    lines = [f"# 10 — Auto-Journal Hub: Every Accounting Integration Point\n",
             f"_Per CLAUDE.md rule 3.1, all accounting writes go through `src/lib/auto-journal.ts`. This file tracks every entry/exit edge of that hub._\n",
             f"\n**Stats:** {len(aj_ids)} nodes inside `auto-journal*` · **{len(incoming)} incoming edges** · **{len(outgoing)} outgoing edges**\n",
             "\n## Auto-Journal nodes\n",
             "| Node | File |",
             "|------|------|"]
    for nid in sorted(aj_ids, key=lambda i: lbl(nodes, i)):
        lines.append(f"| `{lbl(nodes, nid)}` | `{nodes[nid].get('source_file','?')}` |")

    lines.append(f"\n## Callers ({len(callers)} files call into auto-journal)\n")
    for f in sorted(callers, key=lambda f: -len(callers[f])):
        edges_list = callers[f]
        lines.append(f"\n### `{f}` ({len(edges_list)} call edges)")
        seen = set()
        for src, tgt, rel in edges_list:
            key = (src, tgt, rel)
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"- `{src}` --{rel}--> `{tgt}`")

    lines.append(f"\n## Callees ({len(callees)} files auto-journal calls into)\n")
    for f in sorted(callees, key=lambda f: -len(callees[f])):
        edges_list = callees[f]
        lines.append(f"\n### `{f}` ({len(edges_list)} call edges)")
        seen = set()
        for src, tgt, rel in edges_list:
            key = (src, tgt, rel)
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"- `{src}` --{rel}--> `{tgt}`")

    lines.append("\n## Architectural read\n")
