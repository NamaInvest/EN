const file = 'src/lib/translations.ts';
let content = fs.readFileSync(file, 'utf8');

// Strip old Object.assign blocks to keep file clean
content = content.replace(/Object\.assign\(translations\['ar'\], \{[\s\S]*?\}\);/g, '');
content = content.replace(/Object\.assign\(translations\['en'\], \{[\s\S]*?\}\);/g, '');
content = content.replace(/Object\.assign\(translations\['hi'\], \{[\s\S]*?\}\);/g, '');
content = content.replace(/Object\.assign\(translations\['bn'\], \{[\s\S]*?\}\);/g, '');
content = content.replace(/Object\.assign\(translations\['ur'\], \{[\s\S]*?\}\);/g, '');

const genObjectStr = (obj) => {
    return Object.entries(obj).map(([k,v]) => `    "${k}": "${v}",`).join('\\n');
};

const arBlock = genObjectStr(arMappings);
const enBlock = genObjectStr(enMappings);

// Find "ar": {
content = content.replace(/"ar":\s*\{/g, '"ar": {\n' + arBlock);
// Find "en": {
content = content.replace(/"en":\s*\{/g, '"en": {\n' + enBlock);

fs.writeFileSync(file, content, 'utf8');
console.log('Successfully injected static mappings inline into translations.ts');
