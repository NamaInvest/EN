const buildObjLiteral = (obj) => {
    return Object.entries(obj).map(([k, v]) => "        '" + k + "': '" + v + "'").join(',\n') + '\n';
};

try {
    let source = fs.readFileSync('src/lib/i18n.tsx', 'utf8');
    
    let parts = source.split('const translations: Record<Language, Record<string, string>> = {');
    if (parts.length < 2) throw new Error('Could not find start of translations');
    
    let afterTransStart = parts[1];
    let arStart = afterTransStart.indexOf('ar: {');
    let enStart = afterTransStart.indexOf('en: {', arStart);
    
    if (arStart === -1 || enStart === -1) throw new Error('Could not find ar: or en: blocks');
    
    let arBlock = afterTransStart.substring(arStart, enStart).trim();
    if (arBlock.endsWith(',')) arBlock = arBlock.slice(0, -1);
    
    let newEnBlock = '    en: {\n' + buildObjLiteral(enMappings) + '    }';
    let newHiBlock = '    hi: {\n' + buildObjLiteral(hiMappings) + '    }';
    let newBnBlock = '    bn: {\n' + buildObjLiteral(bnMappings) + '    }';
    let newUrBlock = '    ur: {\n' + buildObjLiteral(urMappings) + '    }';
    
    let newTranslations = 'const translations: Record<Language, Record<string, string>> = {\n    ' + arBlock + ',\n\n' + newEnBlock + ',\n\n' + newHiBlock + ',\n\n' + newBnBlock + ',\n\n' + newUrBlock + '\n};';
    
    let contextIdx = source.indexOf('// ============ CONTEXT ============');
    if (contextIdx === -1) throw new Error('Could not find CONTEXT section');
    
    let contextStr = source.substring(contextIdx);
    if(contextStr.includes('Object.assign(')) {
        contextStr = contextStr.split('Object.assign(')[0] + '\n' + contextStr.substring(contextStr.lastIndexOf('export function I18nProvider'));
    }
    
    let finalSource = parts[0] + newTranslations + '\n\n' + contextStr;
    
    fs.writeFileSync('src/lib/i18n.tsx', finalSource, 'utf8');
    console.log('Successfully rebuilt i18n.tsx');
} catch(e) {
    console.error(e);
}
