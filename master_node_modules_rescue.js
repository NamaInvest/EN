const fs = require('fs');
const cp = require('child_process');
const path = require('path');

const nodeExec = process.execPath;
const nodeDir = path.dirname(nodeExec);

const logFile = '/root/master_rescue.log';
fs.writeFileSync(logFile, `Starting EXACT Master Rescue using N1 payload...\n`);

const log = (msg) => {
  console.log(msg);
  fs.appendFileSync(logFile, msg + '\n');
};

const n1NodeModules = '/www/wwwroot/n1.namainvist.com/node_modules';

if (!fs.existsSync(n1NodeModules)) {
    log("FATAL: N1 node_modules does not exist! Aborting.");
    process.exit(1);
}

for (let i = 2; i <= 10; i++) {
  const domain = `n${i}.namainvist.com`;
  const dest = `/www/wwwroot/${domain}`;
  
  if (fs.existsSync(dest)) {
    log(`\n\n=== RECOVERING ${domain} ===`);
    
    // Wipe local corrupted modules
    log(`Wiping defective node_modules on ${domain}...`);
    cp.execSync(`rm -rf ${dest}/node_modules`);
    
    // Copy the holy grail
    log(`Cloning N1 node_modules organic binary payload...`);
    cp.execSync(`cp -r ${n1NodeModules} ${dest}/`);
    
    // Ensure .next is clean to force fresh Turbopack
    log(`Clearing .next cache...`);
    cp.execSync(`rm -rf ${dest}/.next`);

    log(`Freeing port ${3000 + i}...`);
    try { cp.execSync(`fuser -k -9 ${3000 + i}/tcp`); } catch(e) {}

    const buildOpts = { cwd: dest, stdio: 'inherit', env: { ...process.env, PATH: nodeDir + ':' + process.env.PATH } };

    try {
      log(`Compiling native css styling via Next.js...`);
      cp.execSync(`${nodeExec} ./node_modules/.bin/next build`, buildOpts);
      log(`${domain} PERFECTLY HYDRATED AND BUILT!`);
    } catch(e) {
      log(`FAILED TO BUILD ${domain}! ERROR: ${e.message}`);
    }
  }
}

log("\nReloading all PM2 services globally...");
try { cp.execSync(`pm2 reload all`); } catch(e){}
log("ALL DONE AND 100% RECOVERED.");
