const fs = require('fs');
const path = require('path');

const DIR = 'd:\\namasoft9-3-main\\src\\app\\(dashboard)';

function walk(dir) {
    let results = [];
    const list = fs.readdirSync(dir);
    list.forEach(function(file) {
        file = path.join(dir, file);
        const stat = fs.statSync(file);
        if (stat && stat.isDirectory()) { 
            results = results.concat(walk(file));
        } else { 
            if (file.endsWith('.tsx') || file.endsWith('.ts')) {
                results.push(file);
            }
        }
    });
    return results;
}

const files = walk(DIR);
let modifiedCount = 0;

files.forEach(file => {
    let content = fs.readFileSync(file, 'utf8');
    let original = content;

    // Remove legacy dark mode classes and swap gray for slate
    content = content.replace(/dark:bg-gray-800\/80/g, '');
    content = content.replace(/dark:bg-gray-[0-9]{3}\/[0-9]{2}/g, '');
    content = content.replace(/dark:bg-gray-[0-9]{3}/g, '');
    content = content.replace(/dark:text-white/g, '');
    content = content.replace(/dark:text-gray-[0-9]{3}/g, '');
    content = content.replace(/dark:border-gray-[0-9]{3}/g, '');

    // Common complex string replacements for the card structures
    content = content.replace(/bg-white border border-gray-200 rounded-lg shadow-sm/g, 'card');
    content = content.replace(/bg-white border border-gray-[0-9]{3} rounded-[a-z]+/g, 'card');
    content = content.replace(/bg-white shadow-sm rounded-lg border border-gray-[0-9]{3}/g, 'card');

    // Color swaps for premium feel
    content = content.replace(/text-gray-900/g, 'text-slate-900');
    content = content.replace(/text-gray-800/g, 'text-slate-800');
    content = content.replace(/text-gray-700/g, 'text-slate-700');
    content = content.replace(/text-gray-600/g, 'text-slate-600');
    content = content.replace(/text-gray-500/g, 'text-slate-500');
    content = content.replace(/text-gray-400/g, 'text-slate-400');
    
    content = content.replace(/bg-gray-50/g, 'bg-slate-50');
    content = content.replace(/bg-gray-100/g, 'bg-slate-100');
    content = content.replace(/bg-gray-200/g, 'bg-slate-200');

    content = content.replace(/border-gray-100/g, 'border-slate-100');
    content = content.replace(/border-gray-200/g, 'border-slate-200');
    content = content.replace(/border-gray-300/g, 'border-slate-300');

    // Fix up any double spaces generated by regex removals
    content = content.replace(/  +/g, ' ');
    content = content.replace(/ className=" "/g, ' className=""');
    content = content.replace(/ className="\s+/g, ' className="');
    content = content.replace(/\s+"\s/g, ' "');

    if (content !== original) {
        fs.writeFileSync(file, content, 'utf8');
        modifiedCount++;
    }
});

console.log(`✅ Successfully applied Light Professional UI aesthetic to ${modifiedCount} files!`);
